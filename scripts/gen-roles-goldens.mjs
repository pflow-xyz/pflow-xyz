// gen-roles-goldens.mjs — pin public/petri-roles.js to sim's own derivation.
//
//   node scripts/gen-roles-goldens.mjs --sim ../sim-pflow-xyz
//
// Runs sim-pflow-xyz's web/lib/sim-derive.js (deriveRoles, deriveDisruptions)
// on sim-format models and writes parity/roles/<name>.json: the model, the
// rates document sim's console would read, and sim's answer. The test
// (public/petri-roles_test.ts) converts each model to the editor's format and
// requires petri-roles.js to give the same roles and disruptions. Never
// regenerate to make a test pass; regenerate when sim's derivation changes,
// and copy the change into petri-roles.js.
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const i = process.argv.indexOf('--sim');
const sim = resolve(i > 0 ? process.argv[i + 1] : '../sim-pflow-xyz');
const { deriveRoles, deriveDisruptions } = await import(pathToFileURL(join(sim, 'web/lib/sim-derive.js')).href);
const commit = execSync('git log -1 --format=%h -- web/lib/sim-derive.js', { cwd: sim }).toString().trim();

const SOURCES = [
  ['vet-clinic', join(sim, 'services/vet-clinic.json')],
  ['coffeeshop', resolve('parity/ssa/coffeeshop.json')],
  ['erlang-loss', join(sim, 'testdata/fidelity/models/1290209e8b30186b6b6478b2.json')],
  ['vertiport', join(sim, 'testdata/fidelity/models/d8c3d1f2586d3184e37e9416.json')],
  ['voyage-crew', join(sim, 'testdata/fidelity/models/d0040d1f7231df05191b880e.json')],
  ['pix-alert', join(sim, 'testdata/fidelity/models/bd3f15200b11efdb4f84da65.json')],
  ['rwa-settlement', join(sim, 'testdata/fidelity/models/291ea24c8bdb3fba5cfdc6ae.json')],
];

mkdirSync('parity/roles', { recursive: true });
for (const [name, file] of SOURCES) {
  const raw = JSON.parse(readFileSync(file, 'utf8'));
  const m = raw.model || raw;
  // Only what the editor's format can carry: ids, labels, arcs and their
  // types, initial counts and rates (kinetic, guards, stages, tags other
  // than label are dropped before sim derives, so the comparison is fair).
  const labels = { ...(m.presentation?.labels || {}) };
  for (const n of [...(m.places || []), ...(m.transitions || [])]) if (n.tags?.label && !labels[n.id]) labels[n.id] = n.tags.label;
  const model = {
    places: m.places.filter((p) => !p.kind || p.kind === 'token').map((p) => ({ id: p.id, initial: typeof p.initial === 'number' ? p.initial : 0, ...(labels[p.id] ? { tags: { label: labels[p.id] } } : {}) })),
    transitions: m.transitions.map((t) => ({ id: t.id, ...(t.rate !== undefined ? { rate: t.rate } : {}), ...(labels[t.id] ? { tags: { label: labels[t.id] } } : {}) })),
    arcs: m.arcs.map((a) => ({ from: a.from, to: a.to, ...(a.weight && a.weight !== 1 ? { weight: a.weight } : {}), ...(a.type && a.type !== 'normal' ? { type: a.type } : {}) })),
  };
  const rates = {
    initial: Object.fromEntries(model.places.map((p) => [p.id, p.initial])),
    rates: Object.fromEntries(model.transitions.map((t) => [t.id, t.rate ?? 1])),
    classes: [],
  };
  const roles = deriveRoles(model, rates);
  const disruptions = deriveDisruptions(roles, 8);
  writeFileSync(`parity/roles/${name}.json`, JSON.stringify({
    _comment: `Roles golden: sim-pflow-xyz web/lib/sim-derive.js at ${commit} on ${name}. Generated by scripts/gen-roles-goldens.mjs; never regenerate to make a test pass.`,
    model, rates, roles, disruptions,
  }, null, 2) + '\n');
  console.log(`${name}: ${roles.pools.length} pools, ${roles.sources.length} sources, ${roles.losses.length} losses, ${roles.queues.length} queues, ${roles.services.length} services, ${disruptions.length} disruptions`);
}
