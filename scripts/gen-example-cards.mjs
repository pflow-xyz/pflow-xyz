#!/usr/bin/env node
// Write the landing page's example cards (docs/design/agent-first-analysis.md section 16.3, step H4) from
// public/examples.json:
//
//   node scripts/gen-example-cards.mjs           patch the block between the markers in public/index.html
//   node scripts/gen-example-cards.mjs --check   fail if public/index.html is not what this would write
//
// Each card opens into its recorded view, /?cid=<cid>#view=<payload> (the payload is stored with the example: compressed
// bytes differ between runtimes, so the cards are written from the recorded text, not re-compressed), with an "Opens to: ..." line and a quieter
// "Open the canvas" link to the net alone (the old href). Both are plain links, so the cards work with scripts off,
// and all of their text is in the HTML for crawlers. public/examples_test.ts holds index.html to this output.
//
// A card is a <div> holding two links, not an <a> holding a link: anchors do not nest.
// The node: modules are imported where they are used, by a computed specifier (a literal one makes Deno want
// @types/node to type-check, and public/examples_test.ts imports this file).

export const BEGIN = '<!-- examples:cards:begin (generated by scripts/gen-example-cards.mjs from public/examples.json; do not edit by hand) -->';
export const END = '<!-- examples:cards:end -->';

const esc = (s) => String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// The page's old cards put the title in the query as a form value ("Coffee+Shop").
const titleParam = (t) => encodeURIComponent(t).replace(/%20/g, '+');

/** The canvas link: the net alone, as the cards have always opened it. */
export const canvasHref = (e) => `/?cid=${e.cid}&title=${titleParam(e.title)}`;
/** The view link: the same, plus the recorded view in the hash. */
export const viewHref = (e, payload) => `${canvasHref(e)}#view=${payload}`;

/** One card. `payload` is the example's #view= payload (encodeView of its spec). */
export function renderCard(e, payload, indent = '            ') {
    const i = indent;
    return [
        `${i}<div class="model-card" data-example="${esc(e.id)}" data-cid="${esc(e.cid)}" data-title="${esc(e.title)}">`,
        `${i}    <a class="model-card-main" href="${esc(viewHref(e, payload))}">`,
        `${i}        <div class="model-card-img">`,
        `${i}            <img alt="${esc(e.title)}" src="/img/${esc(e.cid)}.svg" loading="lazy"/>`,
        `${i}        </div>`,
        `${i}        <div class="model-card-body">`,
        `${i}            <h3>${esc(e.title)}</h3>`,
        `${i}            <p>${esc(e.blurb)}</p>`,
        `${i}            <span class="model-card-opens">Opens to: ${esc(e.opensTo)}</span>`,
        `${i}        </div>`,
        `${i}    </a>`,
        `${i}    <a class="model-card-canvas" href="${esc(canvasHref(e))}">Open the canvas</a>`,
        `${i}</div>`,
    ].join('\n');
}

/** The whole block, markers included. `payloads` maps example id to payload. */
export function renderBlock(examples, payloads, indent = '            ') {
    return [`${indent}${BEGIN}`, ...examples.map((e) => renderCard(e, payloads[e.id], indent)), `${indent}${END}`].join('\n');
}

/** index.html with the block between the markers replaced by `block`. Throws when the markers are missing. */
export function patch(html, block) {
    const a = html.indexOf(BEGIN);
    const b = html.indexOf(END);
    if (a < 0 || b < 0 || b < a) throw new Error('public/index.html has no example-card markers');
    const start = html.lastIndexOf('\n', a) + 1; // the markers sit on their own lines; the block brings its own indent
    return html.slice(0, start) + block + html.slice(b + END.length);
}

/** The payloads for a list of examples (each example's #view= value, as recorded in examples.json). */
export function payloadsFor(examples) {
    return Object.fromEntries(examples.map((e) => [e.id, e.payload]));
}

if (typeof process !== 'undefined' && import.meta.url === `file://${process.argv[1]}`) {
    const { readFileSync, writeFileSync } = await import(`node:${'fs'}`);
    const { fileURLToPath } = await import(`node:${'url'}`);
    const root = fileURLToPath(new URL('../', import.meta.url));
    const examples = JSON.parse(readFileSync(`${root}public/examples.json`, 'utf8')).examples;
    const html = readFileSync(`${root}public/index.html`, 'utf8');
    const next = patch(html, renderBlock(examples, payloadsFor(examples)));
    if (process.argv.includes('--check')) {
        if (next !== html) { console.error('public/index.html is out of date: run node scripts/gen-example-cards.mjs'); process.exit(1); }
        console.log('public/index.html cards match public/examples.json');
    } else {
        writeFileSync(`${root}public/index.html`, next);
        console.log(`wrote ${examples.length} cards into public/index.html`);
    }
}
