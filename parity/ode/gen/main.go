// Command gen emits parity/ode/expected.json: go-pflow's Tsit5 trajectory
// for every model in parity/ode/fixtures.json, integrated with
// solver.DefaultOptions() (dt=0.01, dtmin=1e-6, dtmax=0.1, abstol=1e-6,
// reltol=1e-3, adaptive).
//
// fixtures.json is hand-formatted and holds only inputs; this file is the
// reference OUTPUT the other implementations are held to. Three consumers
// read it:
//
//   - parity/ode/ode_parity_test.go (Go, exact — it is the generator's own
//     integrator, so anything but bit-equality means go-pflow changed);
//   - parity/ode/ode_expected_test.ts (public/petri-solver.js via deno,
//     1e-12 relative — V8's Math.pow and Go's math.Pow differ by 1-2 ulp on
//     the step controller's fractional exponent, which perturbs dt);
//   - pflow-rs/crates/pflow-solver/tests/ode_parity.rs (a byte-identical copy
//     of both files under tests/fixtures/ode/).
//
// The generator solves each model several times and records whether the
// trajectory is bit-stable across runs. Go iterates maps in randomized order,
// so a place that accumulates three or more flux terms (sir's I: two from
// infect, one from recover) can differ in the last bit between two runs; a
// fixture marked bitStable=false is asserted at a tight relative tolerance
// instead of exactly. Regenerate deliberately with `make ode-expected`.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"runtime/debug"

	"github.com/pflow-xyz/go-pflow/parser"
	"github.com/pflow-xyz/go-pflow/solver"
)

type fixture struct {
	Name  string             `json:"name"`
	Model json.RawMessage    `json:"model"`
	Rates map[string]float64 `json:"rates"`
	Tspan [2]float64         `json:"tspan"`
}

type trajectory struct {
	Name      string               `json:"name"`
	BitStable bool                 `json:"bitStable"`
	Steps     int                  `json:"steps"`
	Places    []string             `json:"places"`
	T         []float64            `json:"t"`
	U         map[string][]float64 `json:"u"`
	Final     map[string]float64   `json:"final"`
}

type expected struct {
	Comment        string       `json:"_comment"`
	Source         string       `json:"source"`
	FixturesSha256 string       `json:"fixturesSha256"`
	GoPflow        string       `json:"goPflow"`
	Options        string       `json:"options"`
	Models         []trajectory `json:"models"`
}

const stabilityRuns = 8

func main() {
	in := flag.String("in", "parity/ode/fixtures.json", "fixture models")
	out := flag.String("out", "parity/ode/expected.json", "output path")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("read fixtures: %v", err)
	}
	var input struct {
		Models []fixture `json:"models"`
	}
	if err := json.Unmarshal(raw, &input); err != nil {
		log.Fatalf("parse fixtures: %v", err)
	}
	sum := sha256.Sum256(raw)

	var models []trajectory
	for _, fx := range input.Models {
		first := solveOnce(fx)
		stable := true
		for r := 1; r < stabilityRuns; r++ {
			if !sameBits(first, solveOnce(fx)) {
				stable = false
				break
			}
		}
		first.BitStable = stable
		models = append(models, first)
	}

	doc := expected{
		Comment: "GENERATED by parity/ode/gen (make ode-expected) — do not edit. go-pflow Tsit5 trajectories for every model in fixtures.json; " +
			"the Go parity test asserts bit-equality where bitStable, the JS replay and pflow-rs assert within 1e-12 relative.",
		Source:         "parity/ode/fixtures.json",
		FixturesSha256: hex.EncodeToString(sum[:]),
		GoPflow:        goPflowVersion(),
		Options:        "solver.DefaultOptions(): dt=0.01 dtmin=1e-6 dtmax=0.1 abstol=1e-6 reltol=1e-3 adaptive",
		Models:         models,
	}
	enc, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, append(enc, '\n'), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s (%d models)\n", *out, len(models))
	for _, m := range models {
		fmt.Printf("  %-22s %4d steps  bitStable=%v\n", m.Name, m.Steps, m.BitStable)
	}
}

func solveOnce(fx fixture) trajectory {
	net, err := parser.FromJSON(fx.Model)
	if err != nil {
		log.Fatalf("%s: parse model: %v", fx.Name, err)
	}
	state := net.SetState(nil)
	rates := net.SetRates(fx.Rates)
	prob := solver.NewProblem(net, state, fx.Tspan, rates)
	sol := solver.Solve(prob, solver.Tsit5(), solver.DefaultOptions())
	if sol.Truncated {
		log.Fatalf("%s: solve truncated", fx.Name)
	}

	// Report per-place totals under the fixture's own place names, like
	// GetFinalState: multi-color models are unfolded internally.
	var places []string
	for p := range state {
		places = append(places, p)
	}
	sortStrings(places)

	tr := trajectory{
		Name:   fx.Name,
		Steps:  len(sol.T) - 1,
		Places: places,
		T:      sol.T,
		U:      map[string][]float64{},
		Final:  sol.GetFinalState(),
	}
	for i := range sol.T {
		st := sol.GetState(i)
		for _, p := range places {
			v := st[p]
			if math.IsNaN(v) || math.IsInf(v, 0) {
				log.Fatalf("%s: non-finite value at step %d place %s", fx.Name, i, p)
			}
			tr.U[p] = append(tr.U[p], v)
		}
	}
	return tr
}

func sameBits(a, b trajectory) bool {
	if len(a.T) != len(b.T) {
		return false
	}
	for i := range a.T {
		if math.Float64bits(a.T[i]) != math.Float64bits(b.T[i]) {
			return false
		}
	}
	for p, row := range a.U {
		for i := range row {
			if math.Float64bits(row[i]) != math.Float64bits(b.U[p][i]) {
				return false
			}
		}
	}
	return true
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// goPflowVersion records which go-pflow produced the file: the pinned module
// version, or the replace target when regenerated against a local checkout.
func goPflowVersion() string {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return "unknown"
	}
	for _, d := range bi.Deps {
		if d.Path == "github.com/pflow-xyz/go-pflow" {
			if d.Replace != nil {
				return d.Replace.Path + " " + d.Replace.Version
			}
			return d.Version
		}
	}
	return "unknown"
}
