// petri-ssa.js — Portable discrete-stochastic simulation (Gillespie direct
// method) that is BYTE-EXACT with go-pflow's `stochastic` package (portable
// path), pflow-rs's `pflow_solver::ssa` and pflow-jl's `simulate_ssa`.
//
// "Byte-exact" means: the same model, options and seed produce the same
// IEEE-754 binary64 ensemble mean, standard deviation and final value at every
// grid time in every language. Three platform-dependent things are therefore
// pinned by construction, and none of them may be replaced by a runtime
// equivalent:
//
//   1. the random stream — SplitMix64 seeding into xoshiro256**, done in
//      BigInt with an explicit 64-bit mask after every +, * and <<;
//   2. the logarithm — `plog`, a port of the pure-Go `math.log` (fdlibm
//      e_log.c form). V8's Math.log is a different, correctly-rounded
//      implementation that disagrees with it on ~7% of inputs (log(3.0) is the
//      canonical witness), so Math.log must never appear on the SSA path;
//   3. arithmetic order — every sum and product below is written in the order
//      the spec fixes. JS has no FMA and does not contract, so what is written
//      is what runs.
//
// The contract is replayed by public/petri-ssa_test.ts against the goldens in
// parity/ssa/*.json — generated by go-pflow's `cmd/ssa-goldens` into
// go-pflow/stochastic/testdata/portable/ (branch discrete-stochastic) and
// copied here byte-identical; parity/ssa/README.md names the generating
// commit and the sha256 of every copy. The goldens are consumed here, never
// produced and never regenerated to make a test pass.
// No DOM, no dependencies beyond ./petri-sim.js (arc-weight normalisation).

import { getArcWeight } from "./petri-sim.js";

// ─── 1. PRNG ────────────────────────────────────────────────────────────────

const M64 = 0xFFFFFFFFFFFFFFFFn;
const SPLITMIX_GAMMA = 0x9E3779B97F4A7C15n;
const SPLITMIX_M1 = 0xBF58476D1CE4E5B9n;
const SPLITMIX_M2 = 0x94D049BB133111EBn;
const TWO_POW_MINUS_53 = 2 ** -53; // 0x3CA0000000000000, exact

function rotl(x, k) {
    return ((x << k) | (x >> (64n - k))) & M64;
}

/**
 * SplitMix64: expand one unsigned 64-bit seed into four xoshiro256** state
 * words. `seed` is a BigInt (or a non-negative integer number below 2^53);
 * arithmetic wraps modulo 2^64.
 * @param {bigint|number} seed
 * @returns {bigint[]} [s0, s1, s2, s3]
 */
export function splitmix64(seed) {
    let x = BigInt(seed) & M64;
    const s = [];
    for (let i = 0; i < 4; i++) {
        x = (x + SPLITMIX_GAMMA) & M64;
        let z = x;
        z = ((z ^ (z >> 30n)) * SPLITMIX_M1) & M64;
        z = ((z ^ (z >> 27n)) * SPLITMIX_M2) & M64;
        z = z ^ (z >> 31n);
        s.push(z);
    }
    return s;
}

/**
 * xoshiro256** generator. `next()` returns the raw 64-bit output as a BigInt;
 * `uniform()` returns a double in [0, 1) with 2^-53 granularity
 * (`float64(next() >> 11) * 2^-53`, both steps exact).
 */
export class Xoshiro256 {
    /** @param {bigint|number} seed */
    constructor(seed) {
        this.s = splitmix64(seed);
    }

    /** @returns {bigint} */
    next() {
        const s = this.s;
        const result = (rotl((s[1] * 5n) & M64, 7n) * 9n) & M64;
        const t = (s[1] << 17n) & M64;
        s[2] = s[2] ^ s[0];
        s[3] = s[3] ^ s[1];
        s[1] = s[1] ^ s[2];
        s[0] = s[0] ^ s[3];
        s[2] = s[2] ^ t;
        s[3] = rotl(s[3], 45n);
        return result;
    }

    /** @returns {number} in [0, 1) */
    uniform() {
        return Number(this.next() >> 11n) * TWO_POW_MINUS_53;
    }
}

// ─── 2. Portable natural log ────────────────────────────────────────────────

// One shared 8-byte view for all bit-level float work (big-endian by default:
// byte offset 0 holds the sign/exponent word).
const dv = new DataView(new ArrayBuffer(8));

function fromBits(hi, lo) {
    dv.setUint32(0, hi);
    dv.setUint32(4, lo);
    return dv.getFloat64(0);
}

const Ln2Hi = fromBits(0x3FE62E42, 0xFEE00000); // 6.93147180369123816490e-01
const Ln2Lo = fromBits(0x3DEA39EF, 0x35793C76); // 1.90821492927058770002e-10
const L1 = fromBits(0x3FE55555, 0x55555593); // 6.666666666666735130e-01
const L2 = fromBits(0x3FD99999, 0x9997FA04); // 3.999999999940941908e-01
const L3 = fromBits(0x3FD24924, 0x94229359); // 2.857142874366239149e-01
const L4 = fromBits(0x3FCC71C5, 0x1D8E78AF); // 2.222219843214978396e-01
const L5 = fromBits(0x3FC74664, 0x96CB03DE); // 1.818357216161805012e-01
const L6 = fromBits(0x3FC39A09, 0xD078C69F); // 1.531383769920937332e-01
const L7 = fromBits(0x3FC2F112, 0xDF3E5244); // 1.479819860511658591e-01
const SQRT2_OVER_2 = fromBits(0x3FE6A09E, 0x667F3BCD); // 0.7071067811865476
const TWO_POW_52 = 4503599627370496; // exact

/**
 * frexp for a positive, finite, non-zero double: returns [frac, exp] with
 * x = frac * 2^exp and frac in [0.5, 1). Operates on the bit pattern so the
 * result cannot depend on a runtime library.
 * @param {number} x
 * @returns {[number, number]}
 */
function frexp(x) {
    dv.setFloat64(0, x);
    let hi = dv.getUint32(0);
    let e = (hi >>> 20) & 0x7FF;
    if (e === 0) {
        // subnormal: normalise first (exact scaling)
        dv.setFloat64(0, x * TWO_POW_52);
        hi = dv.getUint32(0);
        e = ((hi >>> 20) & 0x7FF) - 52;
    }
    const exp = e - 1022;
    // rewrite the exponent field to 0x3FE (1022): keep sign + mantissa bits
    dv.setUint32(0, (hi & 0x800FFFFF) | (0x3FE << 20));
    const frac = dv.getFloat64(0);
    return [frac, exp];
}

/**
 * Portable natural logarithm — the pure-Go `math.log` (fdlibm e_log.c form),
 * every operation in the specified order. Never replace with Math.log.
 * @param {number} x
 * @returns {number}
 */
export function plog(x) {
    if (Number.isNaN(x) || x === Infinity) return x;
    if (x < 0) return NaN;
    if (x === 0) return -Infinity;

    let [f1, ki] = frexp(x);
    if (f1 < SQRT2_OVER_2) {
        f1 = f1 * 2; // exact
        ki = ki - 1;
    }
    const f = f1 - 1;
    const k = ki;

    const s = f / (2 + f);
    const s2 = s * s;
    const s4 = s2 * s2;
    const t1 = s2 * (L1 + (s4 * (L3 + (s4 * (L5 + (s4 * L7))))));
    const t2 = s4 * (L2 + (s4 * (L4 + (s4 * L6))));
    const R = t1 + t2;
    const hfsq = (0.5 * f) * f;
    return (k * Ln2Hi) - (((hfsq - ((s * (hfsq + R)) + (k * Ln2Lo))) - f));
}

// ─── 3. Model compilation ───────────────────────────────────────────────────

/**
 * Number of ways to pick `w` distinguishable tokens from `m` — go-pflow's
 * `combinations`, verbatim: multiply then divide once per i, in that order.
 * @param {number} m
 * @param {number} w
 * @returns {number}
 */
export function combinations(m, w) {
    if (w <= 0) return 1.0;
    if (m < w) return 0.0;
    let result = 1.0;
    for (let i = 0; i < w; i++) {
        result = result * (m - i);
        result = result / (i + 1);
    }
    return result;
}

function scalarWeight(arc) {
    // petri-sim.js's normalisation: absent or scalar 0 → 1 (a bare weight of
    // 0 is a degenerate "unspecified"). Vector (colored) weights are not part
    // of the portable contract; the first component is taken.
    return getArcWeight(arc)[0];
}

function arcType(arc) {
    if (arc.type != null && arc.type !== "") return String(arc.type);
    // Editor-shaped models mark inhibitors with a flag rather than a type.
    if (arc.inhibitTransition) return "inhibitor";
    return "";
}

// An "array index" key per ECMA-262: the canonical decimal string of an
// integer in [0, 2^32 - 2]. Object property enumeration lists these first, in
// ascending numeric order, regardless of insertion order.
function isIntegerLikeKey(k) {
    return /^(0|[1-9][0-9]*)$/.test(k) && Number(k) < 4294967295;
}

/**
 * Places or transitions as an ordered list. Arrays pass through. An object
 * keyed by id is walked in `Object.entries` order, which equals insertion
 * order only when no key is integer-like — otherwise throw, because the
 * order Go would use is unrecoverable from the object.
 * @param {Array|Object|undefined} value
 * @param {string} what
 * @returns {Object[]}
 */
function orderedList(value, what) {
    if (Array.isArray(value)) return value;
    const entries = Object.entries(value || {});
    for (const [id] of entries) {
        if (isIntegerLikeKey(id)) {
            throw new Error(`petri-ssa: ${what} keyed by integer-like id ${JSON.stringify(id)}; JS enumerates such keys out of declaration order, so pass ${what} as an array`);
        }
    }
    return entries.map(([id, x]) => ({ ...x, id: x.id ?? id }));
}

/**
 * Compile a model into the ordered structure the SSA loop consumes.
 *
 * Accepts go-pflow metamodel key names (`places[].{id,initial,capacity}`,
 * `transitions[].{id,rate}`, `arcs[].{from,to,weight,type,kinetic}`) — the
 * shape of the parity fixtures — and, for convenience, the editor's
 * `source`/`target` arc keys and `inhibitTransition` flag. Declaration order
 * is normative: `places` and `transitions` are arrays. An object keyed by id
 * (the editor's place map) is accepted only while insertion order is what
 * `Object.entries` yields: JS enumerates integer-like keys ("0", "1", "42")
 * first, in numeric order, ahead of every other key, so a map with any such
 * key has no declaration order to honour and compile() throws rather than
 * run a different sample path from Go.
 *
 * Rejects `guard` on a transition and non-token place kinds: neither exists in
 * the portable contract, and guessing would silently diverge from Go.
 *
 * @param {Object} model
 * @typedef {{id: string, rate: number, inputs: Array<[number, number, boolean]>, outputs: Array<[number, number]>, reads: Array<[number, number]>, inhibits: Array<[number, number]>, caps: Array<[number, number, number]>}} CompiledTransition
 * @returns {{places: string[], initial: number[], transitions: CompiledTransition[]}}
 */
export function compile(model) {
    const placeList = orderedList(model.places, "places");
    const transitionList = orderedList(model.transitions, "transitions");
    const arcs = (model.arcs || []).map(a => ({
        from: a.from ?? a.source,
        to: a.to ?? a.target,
        weight: scalarWeight(a),
        type: arcType(a),
        kinetic: a.kinetic == null ? true : Boolean(a.kinetic),
    }));

    const places = [];
    const initial = [];
    const capacity = [];
    const idx = new Map();
    for (const p of placeList) {
        if (p.kind != null && p.kind !== "token") {
            throw new Error(`petri-ssa: place ${p.id} has kind ${JSON.stringify(p.kind)}; only token places are portable`);
        }
        idx.set(p.id, places.length);
        places.push(p.id);
        const init = Array.isArray(p.initial) ? Number(p.initial[0] || 0) : Number(p.initial || 0);
        initial.push(init);
        const cap = Array.isArray(p.capacity) ? Number(p.capacity[0] || 0) : Number(p.capacity || 0);
        capacity.push(cap > 0 ? cap : 0);
    }

    const transitions = [];
    for (const t of transitionList) {
        if (t.guard != null) {
            throw new Error(`petri-ssa: transition ${t.id} carries a guard; guards are not part of the portable contract`);
        }
        const rateRaw = Number(t.rate || 0);
        const rate = rateRaw === 0 ? 1.0 : rateRaw;
        const inputs = [];
        const outputs = [];
        const reads = [];
        const inhibits = [];
        const delta = new Map();
        for (const a of arcs) {
            if (a.to === t.id && idx.has(a.from)) {
                const p = idx.get(a.from);
                if (a.type === "inhibitor") {
                    inhibits.push([p, a.weight]);
                } else if (a.type === "read") {
                    reads.push([p, a.weight]);
                } else if (a.type === "") {
                    inputs.push([p, a.weight, a.kinetic]);
                    delta.set(p, (delta.get(p) || 0) - a.weight);
                }
            } else if (a.from === t.id && idx.has(a.to) && a.type === "") {
                const p = idx.get(a.to);
                outputs.push([p, a.weight]);
                delta.set(p, (delta.get(p) || 0) + a.weight);
            }
        }
        const caps = [];
        for (let p = 0; p < places.length; p++) {
            const d = delta.get(p) || 0;
            if (capacity[p] > 0 && d > 0) caps.push([p, d, capacity[p]]);
        }
        transitions.push({ id: t.id, rate, inputs, outputs, reads, inhibits, caps });
    }

    return { places, initial, transitions };
}

function gated(tr, marking) {
    for (const [p, w] of tr.reads) if (marking[p] < w) return false;
    for (const [p, w] of tr.inhibits) if (marking[p] >= w) return false;
    for (const [p, d, limit] of tr.caps) if (marking[p] + d > limit) return false;
    return true;
}

// ─── 4. One realization ─────────────────────────────────────────────────────

const MAX_STEPS = 1_000_000;

/**
 * Run one sample path and return `traj[p][i]`: the marking held at grid time
 * `times[i]` (a jump at exactly `t === times[i]` is not yet applied).
 * @param {Object} compiled - from compile()
 * @param {number[]} marking - initial marking in place order; mutated
 * @param {number[]} times - sample grid
 * @param {Xoshiro256} rng
 * @returns {number[][]}
 */
function realization(compiled, marking, times, rng) {
    const { transitions } = compiled;
    const nP = marking.length;
    const nT = transitions.length;
    const S = times.length;
    const traj = [];
    for (let p = 0; p < nP; p++) traj.push(new Array(S).fill(0));
    const propensity = new Array(nT).fill(0);

    let t = 0.0;
    let next = 0;
    const record = () => {
        while (next < S && times[next] <= t) {
            for (let p = 0; p < nP; p++) traj[p][next] = marking[p];
            next++;
        }
    };

    record();
    const tEnd = times[S - 1]; // NOT options.horizon: they can differ by an ulp
    for (let step = 0; step < MAX_STEPS && t < tEnd; step++) {
        // 1. propensities, strictly in transition order, summed left to right
        let a0 = 0.0;
        for (let j = 0; j < nT; j++) {
            const tr = transitions[j];
            let a = tr.rate;
            for (const [p, w, kinetic] of tr.inputs) {
                const m = marking[p];
                if (m < w) { a = 0; break; }
                if (kinetic) a = a * combinations(m, w);
            }
            if (a > 0 && !gated(tr, marking)) a = 0;
            propensity[j] = a;
            a0 = a0 + a;
        }
        // 2. dead marking: no draw consumed
        if (a0 <= 0) break;
        // 3. waiting time: u = 1 - x1 is exact and in (0, 1]
        const x1 = rng.uniform();
        const u = 1.0 - x1;
        const dt = (-plog(u)) / a0;
        // 4./5. advance (unclipped) and record everything the jump passed
        t = t + dt;
        record();
        // 6. past the horizon: the second draw is NOT taken
        if (t > tEnd) break;
        // 7. choose the transition: inclusive scan, zeros included, first wins
        const x2 = rng.uniform();
        const r = x2 * a0;
        let chosen = nT - 1;
        let acc = 0.0;
        for (let j = 0; j < nT; j++) {
            acc = acc + propensity[j];
            if (r <= acc) { chosen = j; break; }
        }
        // 8. fire
        const tr = transitions[chosen];
        for (const [p, w] of tr.inputs) marking[p] = marking[p] - w;
        for (const [p, w] of tr.outputs) marking[p] = marking[p] + w;
    }
    // hold the final marking through the rest of the grid
    while (next < S) {
        for (let p = 0; p < nP; p++) traj[p][next] = marking[p];
        next++;
    }
    return traj;
}

// ─── 5. Ensemble ────────────────────────────────────────────────────────────

/**
 * Simulate an ensemble of sample paths and return the grid statistics.
 *
 * @param {Object} model - metamodel-shaped (see compile)
 * @param {{horizon: number, samples: number, realizations: number, seed: number|bigint}} options
 *   `samples >= 2`; `seed` is an unsigned 64-bit integer (0 is treated as 1,
 *   mirroring go-pflow); realization r is seeded with `seed + r` (wrapping).
 * @returns {{places: string[], times: number[], series: Object.<string,{values:number[], stddev?:number[]}>, final: Object.<string,number>}}
 */
export function simulate(model, options) {
    const compiled = compile(model);
    const horizon = Number(options.horizon);
    const S = Number(options.samples);
    const R = Number(options.realizations);
    if (!(S >= 2)) throw new Error("petri-ssa: samples must be >= 2");
    if (!(R >= 1)) throw new Error("petri-ssa: realizations must be >= 1");
    let base = BigInt(options.seed ?? 0) & M64;
    if (base === 0n) base = 1n;

    const step = horizon / (S - 1);
    const times = new Array(S);
    for (let i = 0; i < S; i++) times[i] = i * step;

    const nP = compiled.places.length;
    const sums = [];
    const sumsq = [];
    for (let p = 0; p < nP; p++) {
        sums.push(new Array(S).fill(0.0));
        sumsq.push(new Array(S).fill(0.0));
    }

    for (let r = 0; r < R; r++) {
        const rng = new Xoshiro256((base + BigInt(r)) & M64);
        const marking = compiled.initial.slice();
        const traj = realization(compiled, marking, times, rng);
        for (let p = 0; p < nP; p++) {
            const row = traj[p];
            for (let i = 0; i < S; i++) {
                const v = row[i];
                sums[p][i] = sums[p][i] + v;
                sumsq[p][i] = sumsq[p][i] + (v * v);
            }
        }
    }

    const n = R;
    const series = {};
    const final = {};
    for (let p = 0; p < nP; p++) {
        const values = new Array(S);
        for (let i = 0; i < S; i++) values[i] = sums[p][i] / n;
        const entry = { values };
        if (R > 1) {
            const stddev = new Array(S);
            for (let i = 0; i < S; i++) {
                let variance = (sumsq[p][i] / n) - (values[i] * values[i]);
                if (variance < 0) variance = 0.0;
                stddev[i] = Math.sqrt(variance);
            }
            entry.stddev = stddev;
        }
        series[compiled.places[p]] = entry;
        final[compiled.places[p]] = values[S - 1];
    }

    return { places: compiled.places.slice(), times, series, final };
}

export default { splitmix64, Xoshiro256, plog, combinations, compile, simulate };
