/**
 * x^y, correctly rounded, the same bits as pflow-rs' crmath::pow and
 * go-pflow's crmath.Pow. Special cases are C99 Annex F's (as Math.pow's).
 * @param {number} x
 * @param {number} y
 * @returns {number}
 */
export function crPow(x, y) {
  if (y === 0 || x === 1) return 1;
  if (Number.isNaN(x) || Number.isNaN(y)) return NaN;
  const yc = crYClass(y);
  if (y === Infinity || y === -Infinity) {
    const ax = Math.abs(x);
    if (ax === 1) return 1;
    return (ax < 1) === (y > 0) ? 0 : Infinity;
  }
  if (x === 0) {
    const odd = yc === 1;
    if (y < 0) return odd ? 1 / x : Infinity;
    return odd ? x : 0;
  }
  if (x === Infinity) return y < 0 ? 0 : Infinity;
  if (x === -Infinity) {
    const odd = yc === 1;
    if (y < 0) return odd ? -0 : 0;
    return odd ? -Infinity : Infinity;
  }
  if (x < 0) {
    if (yc === 0) return NaN;
    return yc === 1 ? -crPowPos(-x, y) : crPowPos(-x, y);
  }
  return crPowPos(x, y);
}

/** 0: not an integer, 1: an odd integer, 2: an even one. */
function crYClass(y) {
  if (!(Math.abs(y) < CR_TWO53)) return 2;
  const t = Math.trunc(y);
  if (t !== y) return 0;
  return t % 2 !== 0 ? 1 : 2;
}

function crPowPos(x, y) {
  if (x === 1) return 1;
  const [m, e] = crReduce(x);
  // |y ln x| > 1024 for every double x != 1 once |y| >= 2^63.
  if (!(Math.abs(y) < CR_TWO63)) return (x > 1) === (y > 0) ? Infinity : 0;
  const t = crDdMulF(crLnDd(m, e), y);
  if (t[0] > 709.79) return Infinity;
  if (t[0] < -745.2) return 0;
  if (t[0] > -708.0 && t[0] < 709.0) {
    const [p, k] = crExpDd(t);
    if (p[0] === p[0] + p[1] * CR_ROUND) return p[0] * crTwoPow(k);
  }
  return crSlow(m, e, y, t[0]);
}

/** x = m 2^e, m in [sqrt(2)/2, sqrt(2)), for finite x > 0. */
function crReduce(x) {
  let b = crBits(x);
  let ex = Number((b >> 52n) & 0x7FFn);
  if (ex === 0) {
    x = x * crFromBits(0x4330000000000000n);
    b = crBits(x);
    ex = Number((b >> 52n) & 0x7FFn) - 52;
  }
  let e = ex - 1022;
  let m = crFromBits((b & ~(0x7FFn << 52n)) | (1022n << 52n));
  if (m < CR_SQRT2_OVER_2) {
    m = m * 2;
    e -= 1;
  }
  return [m, e];
}

const crTwoPow = (k) => crFromBits(BigInt(k + 1023) << 52n);
const crNearest = (q) => (q >= 0 ? Math.trunc(q + 0.5) : -Math.trunc(0.5 - q));

function crTwoSum(a, b) {
  const s = a + b;
  const bb = s - a;
  return [s, (a - (s - bb)) + (b - bb)];
}

function crQuickTwoSum(a, b) {
  const s = a + b;
  return [s, b - (s - a)];
}

function crSplit(a) {
  const t = CR_SPLITTER * a;
  const hi = t - (t - a);
  return [hi, a - hi];
}

function crTwoProd(a, b) {
  const p = a * b;
  const [ah, al] = crSplit(a);
  const [bh, bl] = crSplit(b);
  return [p, ((ah * bh - p) + ah * bl + al * bh) + al * bl];
}

function crDdAdd(x, y) {
  let [s, e] = crTwoSum(x[0], y[0]);
  const [t, f] = crTwoSum(x[1], y[1]);
  e = e + t;
  [s, e] = crQuickTwoSum(s, e);
  e = e + f;
  return crQuickTwoSum(s, e);
}

const crDdNeg = (x) => [-x[0], -x[1]];

function crDdMul(x, y) {
  let [p, e] = crTwoProd(x[0], y[0]);
  e = e + (x[0] * y[1] + x[1] * y[0]);
  return crQuickTwoSum(p, e);
}

function crDdMulF(x, f) {
  let [p, e] = crTwoProd(x[0], f);
  e = e + x[1] * f;
  return crQuickTwoSum(p, e);
}

function crDdDiv(a, b) {
  let q1 = a[0] / b[0];
  let r = crDdAdd(a, crDdNeg(crDdMulF(b, q1)));
  let q2 = r[0] / b[0];
  r = crDdAdd(r, crDdNeg(crDdMulF(b, q2)));
  const q3 = r[0] / b[0];
  [q1, q2] = crQuickTwoSum(q1, q2);
  return crDdAdd([q1, q2], [q3, 0]);
}

/** ln(m 2^e) in double-double. */
function crLnDd(m, e) {
  const f = m - 1;
  const d = crTwoSum(2, f);
  const s = crDdDiv([f, 0], d);
  const s2 = crDdMul(s, s);
  let p = CR_INV_ODD[CR_INV_ODD.length - 1];
  for (let k = CR_INV_ODD.length - 2; k >= 0; k--) p = crDdAdd(crDdMul(p, s2), CR_INV_ODD[k]);
  let lm = crDdMul(s, p);
  lm = [2 * lm[0], 2 * lm[1]];
  const [p2, pe2] = crTwoProd(e, CR_LN2_2);
  let [h, l] = crTwoSum(e * CR_LN2_1, p2);
  l = l + (pe2 + e * CR_LN2_3);
  [h, l] = crQuickTwoSum(h, l);
  return crDdAdd([h, l], lm);
}

/** exp(t) = p 2^k, for |t[0]| < 709. */
function crExpDd(t) {
  const k = crNearest(t[0] * CR_INV_LN2);
  const [h, l] = crTwoSum(t[0], -(k * CR_LN2_1));
  let r = crDdAdd([h, l], [t[1], 0]);
  const [p, pe] = crTwoProd(k, CR_LN2_2);
  r = crDdAdd(r, [-p, -pe]);
  r = crDdAdd(r, [-(k * CR_LN2_3), 0]);
  let s = CR_INV_FACT[CR_INV_FACT.length - 1];
  for (let n = CR_INV_FACT.length - 2; n >= 0; n--) s = crDdAdd(crDdMul(s, r), CR_INV_FACT[n]);
  return [s, k];
}

/**
 * The slow path: x^y from x = m 2^e in 320-bit fixed point (BigInt, value
 * N / 2^320), rounded once. tHi approximates y ln x, within [-745.2, 709.79].
 */
function crSlow(m, e, y, tHi) {
  const F = 320n;
  const H = 1n << 53n;
  const bigM = BigInt(m * CR_TWO53);
  const sNeg = bigM < H;
  const num = sNeg ? H - bigM : bigM - H;
  const s = (num << F) / (bigM + H);
  const s2 = (s * s) >> F;
  let term = s;
  let sum = s;
  for (let k = 1n; ; k++) {
    term = (term * s2) >> F;
    if (term === 0n) break;
    sum += term / (2n * k + 1n);
  }
  const lnx = (sNeg ? -(sum << 1n) : sum << 1n) + BigInt(e) * CR_LN2_FX;
  const yb = crBits(y);
  const yNeg = yb >> 63n === 1n;
  const yexp = Number((yb >> 52n) & 0x7FFn);
  const frac = yb & ((1n << 52n) - 1n);
  const [ym, ye] = yexp === 0 ? [frac, -1074] : [frac | (1n << 52n), yexp - 1075];
  // Rust and Go truncate the magnitude, so do the same here.
  let tm = (lnx < 0n ? -lnx : lnx) * ym;
  tm = ye >= 0 ? tm << BigInt(ye) : ye > -384 ? tm >> BigInt(-ye) : 0n;
  const tv = (lnx < 0n) !== yNeg ? -tm : tm;
  let k = BigInt(crNearest(tHi * CR_INV_LN2));
  let r = tv - k * CR_LN2_FX;
  while (r < 0n) { k -= 1n; r += CR_LN2_FX; }
  while (r >= CR_LN2_FX) { k += 1n; r -= CR_LN2_FX; }
  let ex = 1n << F;
  term = ex;
  for (let n = 1n; ; n++) {
    term = ((term * r) >> F) / n;
    if (term === 0n) break;
    ex += term;
  }
  return crRoundScaled(ex, Number(k));
}

/** sum 2^k (sum in [1, 2), 320 fractional bits) to the nearest double, ties to even. */
function crRoundScaled(sum, k) {
  if (sum >> 320n >= 2n) { sum >>= 1n; k += 1; }
  const p = k >= -1022 ? 52 : 52 - (-1022 - k);
  if (p < -1) return 0;
  const shift = BigInt(320 - p);
  let mant = sum >> shift;
  const rem = sum & ((1n << shift) - 1n);
  const half = 1n << (shift - 1n);
  const tol = 1n << 70n;
  let up;
  if (half + tol < rem) up = true;
  else if (rem + tol < half) up = false;
  else up = (mant & 1n) === 1n;
  if (up) mant += 1n;
  let ex = k - p;
  if (mant === 1n << 53n) { mant >>= 1n; ex += 1; }
  if (mant >= 1n << 52n) {
    const biased = ex + 52 + 1023;
    if (biased >= 2047) return Infinity;
    return crFromBits((BigInt(biased) << 52n) | (mant - (1n << 52n)));
  }
  return crFromBits(mant);
}

/** The slow path alone, for tests. @param {number} x @param {number} y */
export function crPowSlow(x, y) {
  const [m, e] = crReduce(x);
  const t = crDdMulF(crLnDd(m, e), y);
  return crSlow(m, e, y, t[0]);
}

