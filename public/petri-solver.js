// crPow: a portable, correctly rounded x^y
// ============================================================================
//
// Math.pow is not correctly rounded, and engines differ (V8's is its own
// fdlibm port; Go's math.Pow and the platform libms are wrong on other
// inputs), so the step controller's (1/err)^(1/(order+1)) used to round
// differently in the browser, in go-pflow and in pflow-rs. One ulp in one step
// moves every later step. crPow returns x^y rounded once to the nearest double
// (ties to even), from nothing but + - * /, comparisons and bit casts: an
// operation-for-operation port of pflow-rs' pflow_solver::crmath (the
// reference; its module doc explains the method) and of go-pflow's crmath.Pow.
// parity/crmath/pow.txt holds all of them to the same bits. It lives in this
// file, not its own module, so that every repo vendoring petri-solver.js gets
// it without a new file to pin.

